<?php
// Start the session to manage user authentication
session_start();

// Database connection
$host = 'localhost';
$username = 'root';
$password = '';
$dbname = 'events_db'; // Database name

$conn = new mysqli($host, $username, $password, $dbname);
if ($conn->connect_error) {
    die("Connection failed: " . $conn->connect_error);
}

// Check if selected event IDs are passed
if (isset($_GET['events']) && !empty($_GET['events'])) {
    $selected_event_ids = $_GET['events'];
    $event_ids = implode(',', array_map('intval', $selected_event_ids)); // Sanitize event IDs

    // Fetch events based on selected event IDs
    $sql = "SELECT id, event_name, event_datetime, description FROM events WHERE id IN ($event_ids)";
    $result = $conn->query($sql);
    $selected_events = $result->num_rows > 0 ? $result->fetch_all(MYSQLI_ASSOC) : [];
} else {
    $selected_events = [];
}

$conn->close();

// Include FPDF
require('fpdf/fpdf.php');

// Check if PDF is requested
if (isset($_GET['download_pdf']) && !empty($selected_events)) {
    // Create PDF
    $pdf = new FPDF();
    $pdf->AddPage();
    $pdf->SetFont('Arial', 'B', 12);

    // Title
    $pdf->Cell(0, 10, 'Selected Events Report', 0, 1, 'C');

    // User Info
    $pdf->Cell(0, 10, 'Generated By: ' . $_SESSION['username'], 0, 1);
    $pdf->Cell(0, 10, 'Generated Time: ' . date('Y-m-d H:i:s'), 0, 1);

    // Add Table Header
    $pdf->Ln(10);
    $pdf->Cell(40, 10, 'Event Name', 1);
    $pdf->Cell(40, 10, 'Date & Time', 1);
    $pdf->Cell(60, 10, 'Description', 1);
    $pdf->Ln(10);

    // Add Events to PDF
    foreach ($selected_events as $event) {
        $pdf->Cell(40, 10, $event['event_name'], 1);
        $pdf->Cell(40, 10, $event['event_datetime'], 1);
        $pdf->Cell(60, 10, $event['description'], 1);
        $pdf->Ln(10);
    }

    // Output the PDF
    $pdf->Output('D', 'selected_events_report.pdf');
    exit(); // Stop further execution
}

?>

<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Selected Events</title>
    <style>
        body { font-family: Arial, sans-serif; }
        table { width: 100%; border-collapse: collapse; }
        th, td { padding: 10px; border: 1px solid #ccc; }
        th { background-color: #333; color: white; }
        button { background-color: #333; color: white; padding: 10px 20px; border: none; border-radius: 5px; }
    </style>
</head>
<body>
    <header>
        <h1>Selected Events</h1>
        <nav><a href="?logout=true" style="color: red;">Log Out</a></nav>
    </header>

    <?php if (!empty($selected_events)): ?>
        <table>
            <thead>
                <tr>
                    <th>Event Name</th>
                    <th>Date & Time</th>
                    <th>Description</th>
                </tr>
            </thead>
            <tbody>
                <?php foreach ($selected_events as $event): ?>
                    <tr>
                        <td><?php echo htmlspecialchars($event['event_name']); ?></td>
                        <td><?php echo htmlspecialchars($event['event_datetime']); ?></td>
                        <td><?php echo htmlspecialchars($event['description']); ?></td>
                    </tr>
                <?php endforeach; ?>
            </tbody>
        </table>

        <!-- PDF Download Button -->
        <a href="?download_pdf=true&events=<?php echo implode(',', array_column($selected_events, 'id')); ?>">
            <button>Download PDF</button>
        </a>
    <?php else: ?>
        <p>No events selected.</p>
    <?php endif; ?>
</body>
</html>
