<?php
// Include the FPDF library
require('fpdf/fpdf.php');

// Start the session for user data (e.g., username)
session_start();

// Database connection
$host = 'localhost';
$username = 'root';
$password = '';
$dbname = 'events_db'; // Database name

// Create a connection to the database
$conn = new mysqli($host, $username, $password, $dbname);

// Check for connection error
if ($conn->connect_error) {
    die("Connection failed: " . $conn->connect_error);
}

// Check if selected event IDs are passed from the query string
if (isset($_GET['events']) && !empty($_GET['events'])) {
    $selected_event_ids = $_GET['events'];
    
    // Sanitize the event IDs (to avoid SQL injection)
    $event_ids = implode(',', array_map('intval', $selected_event_ids));
    
    // Fetch events based on selected event IDs
    $sql = "SELECT id, event_name, event_datetime, description FROM events WHERE id IN ($event_ids)";
    $result = $conn->query($sql);
    $selected_events = $result->num_rows > 0 ? $result->fetch_all(MYSQLI_ASSOC) : [];
} else {
    $selected_events = [];
}

// Close the connection
$conn->close();

// Log out functionality
if (isset($_GET['logout'])) {
    session_destroy(); // Destroy the session
    header('Location: work_list.php'); // Redirect to the main page
    exit();
}

// Check if the download button was clicked
if (isset($_POST['download_pdf'])) {
    // Create PDF
    $pdf = new FPDF();
    $pdf->AddPage();
    $pdf->SetFont('Arial', 'B', 16);
    
    // Add title
    $pdf->Cell(200, 10, 'Selected Events Report', 0, 1, 'C');
    
    // Add username and current time
    $pdf->SetFont('Arial', '', 12);
    $pdf->Cell(100, 10, 'Generated by: ' . $_SESSION['username'], 0, 1);
    $pdf->Cell(100, 10, 'Date & Time: ' . date('Y-m-d H:i:s'), 0, 1);
    $pdf->Ln(10);
    
    // Add table headers
    $pdf->Cell(50, 10, 'Event Name', 1, 0, 'C');
    $pdf->Cell(50, 10, 'Date & Time', 1, 0, 'C');
    $pdf->Cell(90, 10, 'Description', 1, 1, 'C');
    
    // Add events data
    foreach ($selected_events as $event) {
        $pdf->Cell(50, 10, $event['event_name'], 1, 0, 'C');
        $pdf->Cell(50, 10, $event['event_datetime'], 1, 0, 'C');
        $pdf->Cell(90, 10, $event['description'], 1, 1, 'C');
    }
    
    // Output the PDF as a download
    $pdf->Output('D', 'selected_events_report.pdf');
    exit();
}
